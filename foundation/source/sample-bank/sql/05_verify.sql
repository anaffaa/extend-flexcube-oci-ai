-- Every accounting reference balances in local currency (expect 0)
SELECT COUNT(*) AS unbalanced_refs FROM (
  SELECT trn_ref_no, event_sr_no FROM FCUBS.ACTB_HISTORY GROUP BY trn_ref_no, event_sr_no
  HAVING ABS(SUM(CASE drcr_ind WHEN 'D' THEN lcy_amount ELSE -lcy_amount END)) > 0.05);

